#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fixtureRoot = path.join(packageRoot, "tests/fixtures/prompt-vault/schema");
const fixtureContract = path.join(fixtureRoot, "client-compatibility.json");
const fixtureSchema = path.join(fixtureRoot, "schema.sql");
const fixtureAnalyticsSchema = path.join(fixtureRoot, "analytics.sql");
const generatedTs = path.join(packageRoot, "src/generatedPromptVaultContract.ts");
const writeMode = process.argv.includes("--write");

const sourceCandidates = [
  process.env.PROMPT_VAULT_ROOT,
  path.resolve(packageRoot, "../../../../../core/prompt-vault"),
  path.join(os.homedir(), "ai-society/core/prompt-vault"),
].filter(Boolean);
const sourceRoot = sourceCandidates.find((candidate) =>
  existsSync(path.join(candidate, "schema/client-compatibility.json")),
);

if (writeMode) {
  if (!sourceRoot) {
    throw new Error("Canonical Prompt Vault source not found; set PROMPT_VAULT_ROOT");
  }
  mkdirSync(fixtureRoot, { recursive: true });
  copyFileSync(path.join(sourceRoot, "schema/client-compatibility.json"), fixtureContract);
  copyFileSync(path.join(sourceRoot, "schema/schema.sql"), fixtureSchema);
  copyFileSync(path.join(sourceRoot, "schema/analytics.sql"), fixtureAnalyticsSchema);
}

if (!existsSync(fixtureContract)) throw new Error(`Missing fixture contract: ${fixtureContract}`);
if (!existsSync(fixtureSchema)) throw new Error(`Missing fixture schema: ${fixtureSchema}`);
if (!existsSync(fixtureAnalyticsSchema))
  throw new Error(`Missing fixture analytics schema: ${fixtureAnalyticsSchema}`);

const contract = JSON.parse(readFileSync(fixtureContract, "utf8"));
const required = contract.required_columns;
const analyticsSchemaSql = readFileSync(fixtureAnalyticsSchema, "utf8");
const generated =
  `// GENERATED by scripts/sync-prompt-vault-contract.mjs — do not edit.\n` +
  `// Source owner: core/prompt-vault/schema/client-compatibility.json\n\n` +
  `export const PROMPT_VAULT_CLIENT_CONTRACT = ${JSON.stringify(contract, null, 2)} as const;\n\n` +
  `export const MIN_SUPPORTED_SCHEMA_VERSION = PROMPT_VAULT_CLIENT_CONTRACT.minimum_supported_schema_version;\n` +
  `export const MAX_TESTED_SCHEMA_VERSION = PROMPT_VAULT_CLIENT_CONTRACT.maximum_tested_schema_version;\n` +
  `export const SUPPORTED_COMPATIBILITY_EPOCH = PROMPT_VAULT_CLIENT_CONTRACT.compatibility_epoch;\n` +
  `export const COMPATIBILITY_EPOCH_INTRODUCED_SCHEMA_VERSION = PROMPT_VAULT_CLIENT_CONTRACT.compatibility_epoch_introduced_schema_version;\n` +
  `export const ANALYTICS_SCHEMA_VERSION = PROMPT_VAULT_CLIENT_CONTRACT.analytics_schema_version;\n` +
  `export const ANALYTICS_SCHEMA_SQL = ${JSON.stringify(analyticsSchemaSql)};\n` +
  `export const REQUIRED_PROMPT_TEMPLATE_COLUMNS = ${JSON.stringify(required.prompt_templates, null, 2)} as const;\n` +
  `export const REQUIRED_EXECUTION_COLUMNS = ${JSON.stringify(required.executions, null, 2)} as const;\n` +
  `export const REQUIRED_FEEDBACK_COLUMNS = ${JSON.stringify(required.feedback, null, 2)} as const;\n`;

function biomeFormatTypeScript(source) {
  const biome = path.join(packageRoot, "node_modules/.bin/biome");
  if (!existsSync(biome)) throw new Error(`Biome executable not found: ${biome}`);
  const tempRoot = mkdtempSync(path.join(os.tmpdir(), "prompt-vault-contract-"));
  const tempFile = path.join(tempRoot, "generatedPromptVaultContract.ts");
  try {
    writeFileSync(tempFile, source, "utf8");
    const result = spawnSync(biome, ["format", "--write", tempFile], {
      cwd: packageRoot,
      encoding: "utf8",
    });
    if (result.status !== 0) throw new Error(result.stderr || result.stdout || "Biome failed");
    return readFileSync(tempFile, "utf8");
  } finally {
    rmSync(tempRoot, { recursive: true, force: true });
  }
}

const formattedGenerated = biomeFormatTypeScript(generated);
if (writeMode) {
  writeFileSync(generatedTs, formattedGenerated, "utf8");
} else if (!existsSync(generatedTs) || readFileSync(generatedTs, "utf8") !== formattedGenerated) {
  throw new Error(
    "Generated Prompt Vault contract is stale; run npm run sync:prompt-vault-contract",
  );
}

if (sourceRoot) {
  const pairs = [
    [path.join(sourceRoot, "schema/client-compatibility.json"), fixtureContract],
    [path.join(sourceRoot, "schema/schema.sql"), fixtureSchema],
    [path.join(sourceRoot, "schema/analytics.sql"), fixtureAnalyticsSchema],
  ];
  for (const [source, fixture] of pairs) {
    if (readFileSync(source, "utf8") !== readFileSync(fixture, "utf8")) {
      throw new Error(
        `Prompt Vault fixture drift: ${path.relative(packageRoot, fixture)} differs from ${source}`,
      );
    }
  }
}

console.log(
  `Prompt Vault contract ${writeMode ? "synced" : "verified"} (schema v${contract.schema_version}, epoch ${contract.compatibility_epoch})`,
);
