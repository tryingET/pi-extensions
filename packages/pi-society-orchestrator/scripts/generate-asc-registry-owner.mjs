#!/usr/bin/env node
/**
 * summary: "Generate GOVERNED_RUNTIME_ASC_REGISTRY_OWNER from the package lock."
 * read_when:
 *   - "Bumping the ASC lock pin or checking generated owner drift."
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ASC_PACKAGE_NAME = "@tryinget/pi-autonomous-session-control";
export const GENERATED_ASC_OWNER_RELATIVE_PATH =
  "src/runtime/governed-runtime-asc-owner.generated.ts";
export const ASC_REGISTRY_OWNER_CONSUMER = "packages/pi-society-orchestrator";
export const ASC_REGISTRY_OWNER_SPECIFIERS = [
  "@tryinget/pi-autonomous-session-control/execution",
  "@tryinget/pi-autonomous-session-control",
];

const ASC_LOCK_KEY = `node_modules/${ASC_PACKAGE_NAME}`;

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

export function loadAscRegistryOwnerFromLock({
  pkg,
  lock,
  consumer = ASC_REGISTRY_OWNER_CONSUMER,
  specifiers = ASC_REGISTRY_OWNER_SPECIFIERS,
} = {}) {
  const issues = [];
  const selector = pkg?.dependencies?.[ASC_PACKAGE_NAME];
  const lockEntry = lock?.packages?.[ASC_LOCK_KEY];

  if (typeof selector !== "string" || selector.trim().length === 0) {
    issues.push(`package.json dependencies.${ASC_PACKAGE_NAME} is required.`);
  }
  if (!isRecord(lockEntry)) {
    issues.push(`package-lock.json is missing ${ASC_LOCK_KEY}.`);
  } else if (lockEntry.link === true) {
    issues.push("ASC package-lock entry is a local link; registry artifact proof is required.");
  }

  const version = isRecord(lockEntry) ? lockEntry.version : null;
  const resolved = isRecord(lockEntry) ? lockEntry.resolved : null;
  const integrity = isRecord(lockEntry) ? lockEntry.integrity : null;
  if (typeof version !== "string" || version.length === 0) {
    issues.push("ASC package-lock entry is missing a version.");
  }
  if (typeof resolved !== "string" || !resolved.startsWith("https://registry.npmjs.org/")) {
    issues.push("ASC package-lock entry is missing a canonical npm registry tarball URL.");
  }
  if (typeof integrity !== "string" || !/^sha512-[A-Za-z0-9+/]+={0,2}$/.test(integrity)) {
    issues.push("ASC package-lock entry is missing a sha512 integrity value.");
  }

  if (issues.length > 0) {
    return { ok: false, issues, owner: null };
  }

  return {
    ok: true,
    issues: [],
    owner: {
      consumer,
      name: ASC_PACKAGE_NAME,
      version,
      selector: selector.trim(),
      url: resolved,
      integrity,
      specifiers: [...specifiers],
    },
  };
}

export function renderAscRegistryOwnerSource(owner) {
  const specifiers = owner.specifiers
    .map((specifier) => `    ${JSON.stringify(specifier)},`)
    .join("\n");
  return `// Generated by scripts/generate-asc-registry-owner.mjs from package-lock.json.
// Do not edit by hand. A lock bump is the pin bump: rerun the generator.

export const GOVERNED_RUNTIME_ASC_REGISTRY_OWNER = {
  consumer: ${JSON.stringify(owner.consumer)},
  name: ${JSON.stringify(owner.name)},
  version: ${JSON.stringify(owner.version)},
  selector: ${JSON.stringify(owner.selector)},
  url: ${JSON.stringify(owner.url)},
  integrity:
    ${JSON.stringify(owner.integrity)},
  specifiers: [
${specifiers}
  ],
} as const;
`;
}

export function syncGeneratedAscRegistryOwner(packageDir, { check = false, pkg, lock } = {}) {
  const manifest = pkg ?? readJson(path.join(packageDir, "package.json"));
  const packageLock = lock ?? readJson(path.join(packageDir, "package-lock.json"));
  const loaded = loadAscRegistryOwnerFromLock({ pkg: manifest, lock: packageLock });
  if (!loaded.ok) {
    return loaded;
  }

  const expectedSource = renderAscRegistryOwnerSource(loaded.owner);
  const targetPath = path.join(packageDir, GENERATED_ASC_OWNER_RELATIVE_PATH);
  const existingSource = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, "utf8") : null;

  if (existingSource === expectedSource) {
    return { ok: true, issues: [], owner: loaded.owner, path: targetPath, changed: false };
  }

  if (check) {
    return {
      ok: false,
      issues: [
        existingSource === null
          ? `Missing generated ASC owner at ${GENERATED_ASC_OWNER_RELATIVE_PATH}; run node scripts/generate-asc-registry-owner.mjs`
          : `Generated ASC owner is stale versus package-lock.json; run node scripts/generate-asc-registry-owner.mjs`,
      ],
      owner: loaded.owner,
      path: targetPath,
      changed: true,
    };
  }

  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, expectedSource);
  return { ok: true, issues: [], owner: loaded.owner, path: targetPath, changed: true };
}

function main() {
  const packageDir = process.cwd();
  const check = process.argv.includes("--check");
  const result = syncGeneratedAscRegistryOwner(packageDir, { check });
  if (!result.ok) {
    for (const issue of result.issues) console.error(issue);
    process.exit(1);
  }
  if (check) {
    console.log(
      `ASC registry owner ${GENERATED_ASC_OWNER_RELATIVE_PATH} matches package-lock.json.`,
    );
    return;
  }
  console.log(
    result.changed
      ? `Wrote ${GENERATED_ASC_OWNER_RELATIVE_PATH} from package-lock.json (${result.owner.name}@${result.owner.version}).`
      : `${GENERATED_ASC_OWNER_RELATIVE_PATH} already matches package-lock.json.`,
  );
}

const entryPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (entryPath && entryPath === fileURLToPath(import.meta.url)) {
  main();
}
