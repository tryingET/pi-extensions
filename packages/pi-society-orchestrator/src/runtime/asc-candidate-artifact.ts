// Retained candidate bytes are NOT registry provenance or publication authority.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { lstatSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, isAbsolute, resolve, sep } from "node:path";

export const ASC_CANDIDATE_SCHEMA = "pi.asc-candidate-artifact.v1";
export const ASC_NAME = "@tryinget/pi-autonomous-session-control";
export const ASC_SOURCE_PATH = "packages/pi-autonomous-session-control";
export const ASC_CONSUMER_PATH = "packages/pi-society-orchestrator";
export const ASC_PLAN_PATH = "policy/asc-candidate-plan.json";
export const ASC_EXECUTION_VALUES = [
  "ASC_EXECUTION_OBSERVATION_EVENT",
  "createAscExecutionRuntime",
  "createSubagentState",
  "getDispatchSubagentDisplayOutput",
  "projectAscExecutionFailure",
  "projectAscExecutionGroupTerminal",
  "projectAscExecutionResult",
  "projectAscExecutionUpdate",
];
export function renderAscRegistryOwnerSource(owner: {
  consumer: string;
  name: string;
  version: string;
  selector: string;
  url: string;
  integrity: string;
  specifiers: readonly string[];
}): string {
  const specifiers = owner.specifiers
    .map((specifier) => `    ${JSON.stringify(specifier)},`)
    .join("\n");
  return `// Generated by scripts/generate-asc-registry-owner.mjs from package-lock.json.
// Do not edit by hand. A lock bump is the pin bump: rerun the generator.

export const GOVERNED_RUNTIME_ASC_REGISTRY_OWNER = {
  consumer: ${JSON.stringify(owner.consumer)},
  name: ${JSON.stringify(owner.name)},
  version: ${JSON.stringify(owner.version)},
  selector: ${JSON.stringify(owner.selector)},
  url: ${JSON.stringify(owner.url)},
  integrity:
    ${JSON.stringify(owner.integrity)},
  specifiers: [
${specifiers}
  ],
} as const;
`;
}
export interface AscCandidateArtifact {
  name: string;
  version: string;
  sha256: string;
  integrity: string;
  size: number;
  relativePath: string;
}
export interface AscCandidateReceipt {
  schema: typeof ASC_CANDIDATE_SCHEMA;
  evidenceKind: "retained_candidate_artifact";
  publicationAuthorized: false;
  registryProvenance: false;
  qualification: "isolated_installed_execution";
  sourceCommit: string;
  sourceInputs: Record<string, string>;
  selector: string;
  artifact: AscCandidateArtifact;
}
export function ascArtifactHashes(bytes: Buffer): {
  sha256: string;
  integrity: string;
  size: number;
} {
  return {
    sha256: createHash("sha256").update(bytes).digest("hex"),
    integrity: `sha512-${createHash("sha512").update(bytes).digest("base64")}`,
    size: bytes.length,
  };
}
export function ascCanonicalUrl(version: string): string {
  return `https://registry.npmjs.org/@tryinget/pi-autonomous-session-control/-/pi-autonomous-session-control-${version}.tgz`;
}
export function ascVersionInRange(version: string, range: string): boolean {
  const parse = (value: string) => /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.exec(value);
  const v = parse(version),
    r = parse(range.replace(/^\^/, ""));
  if (!v || !r) return false;
  if (!range.startsWith("^")) return version === range;
  const [major, minor, patch] = v.slice(1).map(Number);
  const [a, b, c] = r.slice(1).map(Number);
  return (
    major === a &&
    (a > 0
      ? minor > b || (minor === b && patch >= c)
      : minor === b && (b > 0 ? patch >= c : patch === c))
  );
}
interface AscManifest {
  name?: string;
  version?: string;
  dependencies?: Record<string, string>;
}
interface AscLock {
  lockfileVersion?: number;
  packages?: Record<
    string,
    {
      version?: string;
      resolved?: string;
      integrity?: string;
      link?: boolean;
      dependencies?: Record<string, string>;
    }
  >;
}
interface AscPlan {
  schema: string;
  evidenceKind: string;
  registryProvenance: boolean;
  publicationAuthorized: boolean;
  selector: string;
  sourceInputs: Record<string, string>;
  artifact: AscCandidateArtifact;
}
function json<T>(file: string): T {
  return JSON.parse(readFileSync(file, "utf8")) as T;
}
export function verifyAscCandidateBinding(
  receipt: Omit<AscCandidateReceipt, "qualification">,
  head: string,
  inputs: Record<string, string>,
  source: AscManifest,
  consumer: AscManifest,
  plan: AscPlan,
): void {
  assert.equal(receipt.schema, ASC_CANDIDATE_SCHEMA, "Not candidate evidence");
  assert.equal(receipt.evidenceKind, "retained_candidate_artifact");
  assert.equal(receipt.publicationAuthorized, false, "Candidate cannot authorize publication");
  assert.equal(receipt.registryProvenance, false, "Candidate cannot prove registry provenance");
  assert(/^[0-9a-f]{40}$/.test(receipt.sourceCommit), "Candidate requires exact source SHA");
  assert.equal(receipt.sourceCommit, head, "Candidate source SHA mismatch");
  assert.deepEqual(receipt.sourceInputs, inputs, "Candidate source inputs changed");
  assert.equal(source.name, ASC_NAME);
  assert.equal(source.version, receipt.artifact.version, "Candidate source version mismatch");
  assert.equal(consumer.dependencies?.[ASC_NAME], receipt.selector, "Candidate selector mismatch");
  assert(
    ascVersionInRange(receipt.artifact.version, receipt.selector),
    "Candidate version does not satisfy selector",
  );
  assert.equal(plan.schema, "pi.asc-candidate-plan.v1", "Candidate requires planned handoff");
  assert.equal(plan.evidenceKind, "planned_artifact_identity");
  assert.equal(plan.registryProvenance, false);
  assert.equal(plan.publicationAuthorized, false);
  assert.equal(plan.selector, receipt.selector);
  assert.deepEqual(plan.sourceInputs, inputs, "Planned source inputs changed");
  assert.deepEqual(plan.artifact, receipt.artifact, "Candidate bytes differ from planned identity");
}
function physicalFile(file: string): Buffer {
  assert.equal(lstatSync(file).isSymbolicLink(), false, `Candidate file is a link: ${file}`);
  assert.equal(realpathSync(file), resolve(file), `Candidate file path is not physical: ${file}`);
  assert(lstatSync(file).isFile(), `Candidate is not a regular file: ${file}`);
  return readFileSync(file);
}
export function ascSourceInputs(root: string): Record<string, string> {
  return trackedSourceInputs(root, ASC_SOURCE_PATH);
}
export function ascConsumerSourceInputs(root: string): Record<string, string> {
  return trackedSourceInputs(root, ASC_CONSUMER_PATH);
}
function trackedSourceInputs(root: string, sourcePath: string): Record<string, string> {
  const paths = execFileSync("git", ["ls-files", "-z", "--", sourcePath], { cwd: root })
    .toString()
    .split("\0")
    .filter(Boolean)
    .sort();
  assert(paths.length > 0, "Candidate has no tracked ASC inputs");
  return Object.fromEntries(
    paths.map((file) => [file, ascArtifactHashes(physicalFile(resolve(root, file))).sha256]),
  );
}
export function verifyAscCandidateArtifact(
  artifact: AscCandidateArtifact,
  directory: string,
): string {
  assert.equal(artifact.name, ASC_NAME);
  assert(ascVersionInRange(artifact.version, artifact.version), "Invalid candidate version");
  assert(
    artifact.relativePath &&
      !isAbsolute(artifact.relativePath) &&
      !artifact.relativePath.split(/[\\/]/).includes(".."),
  );
  const file = resolve(directory, artifact.relativePath);
  assert(file.startsWith(`${resolve(directory)}${sep}`), "Candidate tarball escapes receipt");
  const bytes = physicalFile(file);
  const hashes = ascArtifactHashes(bytes);
  for (const key of ["sha256", "integrity", "size"] as const)
    assert.equal(hashes[key], artifact[key], `Candidate ${key} mismatch`);
  const pkg = JSON.parse(
    execFileSync("tar", ["-xOf", file, "package/package.json"], { encoding: "utf8" }),
  );
  assert.equal(pkg.name, artifact.name, "Candidate tarball name mismatch");
  assert.equal(pkg.version, artifact.version, "Candidate tarball version mismatch");
  return file;
}
type AscCandidateEvidence = Omit<AscCandidateReceipt, "qualification"> & {
  qualification: "pending" | "isolated_installed_execution";
};
export function verifyAscCandidateReceipt(root: string, receiptPath: string): AscCandidateReceipt {
  return verifyAscCandidateSourceEvidence(
    root,
    receiptPath,
    "isolated_installed_execution",
  ) as AscCandidateReceipt;
}
export function verifyAscCandidatePending(root: string, receiptPath: string): AscCandidateEvidence {
  return verifyAscCandidateSourceEvidence(root, receiptPath, "pending");
}
function verifyAscCandidateSourceEvidence(
  root: string,
  receiptPath: string,
  qualification: AscCandidateEvidence["qualification"],
): AscCandidateEvidence {
  const receipt = JSON.parse(physicalFile(resolve(receiptPath)).toString()) as AscCandidateEvidence;
  assert.equal(receipt.qualification, qualification, "Candidate qualification phase mismatch");
  assert.equal(receipt.schema, ASC_CANDIDATE_SCHEMA, "Not candidate evidence");
  assert.equal(receipt.evidenceKind, "retained_candidate_artifact");
  assert.equal(receipt.publicationAuthorized, false, "Candidate cannot authorize publication");
  assert.equal(receipt.registryProvenance, false, "Candidate cannot prove registry provenance");
  const head = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  assert(/^[0-9a-f]{40}$/.test(receipt.sourceCommit), "Candidate requires exact source SHA");
  assert.equal(receipt.sourceCommit, head, "Candidate source SHA mismatch");
  const inputs = ascSourceInputs(root);
  assert.deepEqual(receipt.sourceInputs, inputs, "Candidate source inputs changed");
  // Bind to the immutable head, not a dirty source merely claiming its SHA.
  for (const [file, hash] of Object.entries(inputs)) {
    const committed = execFileSync("git", ["show", `${head}:${file}`], {
      cwd: root,
      maxBuffer: 64 * 1024 * 1024,
    });
    assert.equal(
      ascArtifactHashes(committed).sha256,
      hash,
      `Uncommitted candidate source: ${file}`,
    );
  }
  for (const file of [
    ASC_PLAN_PATH,
    `${ASC_CONSUMER_PATH}/package.json`,
    `${ASC_CONSUMER_PATH}/package-lock.json`,
    `${ASC_CONSUMER_PATH}/src/runtime/governed-runtime-asc-owner.generated.ts`,
  ]) {
    const committed = execFileSync("git", ["show", `${head}:${file}`], {
      cwd: root,
      maxBuffer: 64 * 1024 * 1024,
    });
    assert.deepEqual(
      physicalFile(resolve(root, file)),
      committed,
      `Uncommitted candidate handoff: ${file}`,
    );
  }
  const source = json<AscManifest>(resolve(root, ASC_SOURCE_PATH, "package.json"));
  const consumer = json<AscManifest>(resolve(root, ASC_CONSUMER_PATH, "package.json"));
  const plan = json<
    AscPlan & {
      consumerSourceInputs: Record<string, string>;
      consumerArtifact: AscCandidateArtifact;
    }
  >(resolve(root, ASC_PLAN_PATH));
  const consumerInputs = ascConsumerSourceInputs(root);
  assert.deepEqual(
    plan.consumerSourceInputs,
    consumerInputs,
    "Planned consumer source inputs changed",
  );
  assert.equal(plan.consumerArtifact?.name, "@tryinget/pi-society-orchestrator");
  assert.equal(
    plan.consumerArtifact?.version,
    consumer.version,
    "Planned consumer version mismatch",
  );
  for (const [file, hash] of Object.entries(consumerInputs)) {
    const committed = execFileSync("git", ["show", `${head}:${file}`], {
      cwd: root,
      maxBuffer: 64 * 1024 * 1024,
    });
    assert.equal(
      ascArtifactHashes(committed).sha256,
      hash,
      `Uncommitted candidate consumer: ${file}`,
    );
  }
  verifyAscCandidateBinding(receipt, head, inputs, source, consumer, plan);
  const regular = json<AscLock>(resolve(root, ASC_CONSUMER_PATH, "package-lock.json"));
  verifyAscCandidateLocks(receipt, consumer, regular);
  const expectedOwner = renderAscRegistryOwnerSource({
    consumer: ASC_CONSUMER_PATH,
    name: ASC_NAME,
    version: receipt.artifact.version,
    selector: receipt.selector,
    url: ascCanonicalUrl(receipt.artifact.version),
    integrity: receipt.artifact.integrity,
    specifiers: [`${ASC_NAME}/execution`, ASC_NAME],
  });
  assert.equal(
    readFileSync(
      resolve(root, ASC_CONSUMER_PATH, "src/runtime/governed-runtime-asc-owner.generated.ts"),
      "utf8",
    ),
    expectedOwner,
    "Candidate generated owner does not match retained artifact",
  );
  verifyAscCandidateArtifact(receipt.artifact, dirname(resolve(receiptPath)));
  return receipt;
}
export function verifyAscCandidateLocks(
  receipt: Pick<AscCandidateReceipt, "selector" | "artifact">,
  pkg: AscManifest,
  regular: AscLock,
  hidden?: AscLock,
): void {
  const key = `node_modules/${ASC_NAME}`;
  assert.equal(
    pkg.dependencies?.[ASC_NAME],
    receipt.selector,
    "Candidate manifest selector mismatch",
  );
  assert.equal(
    regular.packages?.[""]?.dependencies?.[ASC_NAME],
    receipt.selector,
    "Candidate root lock mismatch",
  );
  for (const lock of hidden ? [regular, hidden] : [regular]) {
    assert.equal(lock.lockfileVersion, 3, "Candidate lock must be v3");
    const entry = lock.packages?.[key];
    assert(entry && !entry.link, "Candidate owner cannot be a source link");
    assert.equal(entry.version, receipt.artifact.version, "Candidate lock version mismatch");
    assert.equal(
      entry.resolved,
      ascCanonicalUrl(receipt.artifact.version),
      "Candidate planned URL mismatch",
    );
    assert.equal(entry.integrity, receipt.artifact.integrity, "Candidate lock integrity mismatch");
    assert.deepEqual(
      Object.keys(lock.packages ?? {}).filter((p) => p.includes("pi-autonomous-session-control")),
      [key],
      "Duplicate candidate owner",
    );
  }
}
export function verifyAscCandidateInstalled(
  root: string,
  receiptPath: string,
  consumerRoot: string,
): AscCandidateReceipt {
  const receipt = verifyAscCandidateReceipt(root, receiptPath);
  const modules = realpathSync(resolve(consumerRoot, "node_modules"));
  const owner = resolve(modules, ...ASC_NAME.split("/"));
  assert(
    lstatSync(owner).isDirectory() && !lstatSync(owner).isSymbolicLink(),
    "Candidate owner must be a physical installed artifact",
  );
  assert.equal(realpathSync(owner), owner, "Candidate owner escapes physical install");
  verifyAscCandidateLocks(
    receipt,
    json(resolve(consumerRoot, "package.json")),
    json(resolve(consumerRoot, "package-lock.json")),
    json(resolve(modules, ".package-lock.json")),
  );
  const tarball = verifyAscCandidateArtifact(receipt.artifact, dirname(resolve(receiptPath)));
  verifyAscInstalledContent(owner, tarball, receipt.artifact.version, consumerRoot);
  return receipt;
}
export function verifyAscInstalledContent(
  owner: string,
  tarball: string,
  version: string,
  consumerRoot: string,
): void {
  assert(
    lstatSync(owner).isDirectory() && !lstatSync(owner).isSymbolicLink(),
    "Candidate owner must be a physical installed artifact",
  );
  assert.equal(realpathSync(owner), owner, "Candidate owner escapes physical install");
  const physicalOwners = new Set<string>();
  const seenModules = new Set<string>();
  const inspectModules = (modules: string): void => {
    if (seenModules.has(modules)) return;
    seenModules.add(modules);
    const inspectPackage = (directory: string): void => {
      const manifest = resolve(directory, "package.json");
      try {
        if (json<AscManifest>(manifest).name === ASC_NAME)
          physicalOwners.add(realpathSync(directory));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
      const nested = resolve(directory, "node_modules");
      if (lstatSync(nested, { throwIfNoEntry: false })?.isDirectory())
        inspectModules(realpathSync(nested));
    };
    for (const entry of readdirSync(modules, { withFileTypes: true })) {
      const directory = resolve(modules, entry.name);
      if (entry.isSymbolicLink()) {
        if (entry.name === "pi-autonomous-session-control") inspectPackage(directory);
        continue;
      }
      if (!entry.isDirectory() || entry.name === ".bin") continue;
      if (entry.name.startsWith("@")) {
        for (const scoped of readdirSync(directory, { withFileTypes: true })) {
          if (
            scoped.isDirectory() ||
            (scoped.isSymbolicLink() && scoped.name === "pi-autonomous-session-control")
          )
            inspectPackage(resolve(directory, scoped.name));
        }
      } else inspectPackage(directory);
    }
  };
  inspectModules(realpathSync(resolve(consumerRoot, "node_modules")));
  assert.deepEqual([...physicalOwners], [owner], "Duplicate physical candidate owner");
  const pkg = json<AscManifest>(resolve(owner, "package.json"));
  assert.equal(pkg.name, ASC_NAME);
  assert.equal(pkg.version, version);
  const entries = execFileSync("tar", ["-tzf", tarball], { encoding: "utf8" }).trim().split("\n");
  const packedFiles = new Set<string>();
  for (const entry of entries) {
    assert(
      entry.startsWith("package/") && !entry.split("/").includes(".."),
      "Unsafe candidate tar entry",
    );
    if (entry.endsWith("/")) continue;
    const relative = entry.slice("package/".length);
    assert(!packedFiles.has(relative), "Duplicate candidate tar entry");
    packedFiles.add(relative);
    const expected = execFileSync("tar", ["-xOf", tarball, entry], { maxBuffer: 64 * 1024 * 1024 });
    assert.deepEqual(
      physicalFile(resolve(owner, relative)),
      expected,
      `Installed candidate bytes differ: ${relative}`,
    );
  }
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name === "node_modules") continue;
      const file = resolve(dir, entry.name);
      assert(!entry.isSymbolicLink(), "Installed candidate contains source link");
      if (entry.isDirectory()) walk(file);
      else
        assert(
          packedFiles.has(file.slice(owner.length + 1)),
          "Installed candidate has unqualified extra bytes",
        );
    }
  };
  walk(owner);
  const require = createRequire(resolve(consumerRoot, "package.json"));
  for (const spec of [ASC_NAME, `${ASC_NAME}/execution`]) {
    assert(
      realpathSync(require.resolve(spec)).startsWith(`${owner}${sep}`),
      "Candidate imports resolve to different owner",
    );
  }
  const execution = require(`${ASC_NAME}/execution`);
  for (const name of ASC_EXECUTION_VALUES) {
    assert.equal(
      typeof execution[name],
      name === "ASC_EXECUTION_OBSERVATION_EVENT" ? "string" : "function",
      `Broken candidate execution export: ${name}`,
    );
  }
}
